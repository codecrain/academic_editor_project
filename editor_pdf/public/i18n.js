let currentLocale = 'ko';

function normalizeLocale(value) {
  const normalized = String(value || '').trim().toLowerCase().replace('_', '-');
  if (normalized.startsWith('en')) return 'en';
  if (normalized.startsWith('ko')) return 'ko';
  return '';
}

function resolveInitialLocale() {
  const query = new URLSearchParams(window.location.search);
  const requested = normalizeLocale(query.get('lang') || query.get('locale'));
  if (requested) return requested;
  try {
    const saved = normalizeLocale(window.localStorage.getItem(LOCALE_STORAGE_KEY));
    if (saved) return saved;
  } catch {
    // Storage may be unavailable in a sandboxed embed; browser language remains sufficient.
  }
  return normalizeLocale(navigator.language) || 'ko';
}

function interpolate(value, variables = {}) {
  return String(value).replace(/\{(\w+)\}/gu, (_match, name) => String(variables[name] ?? `{${name}}`));
}

export function getLocale() {
  return currentLocale;
}

export function setLocale(value) {
  const normalized = normalizeLocale(value);
  if (!SUPPORTED_LOCALES.has(normalized)) return currentLocale;
  currentLocale = normalized;
  try { window.localStorage.setItem(LOCALE_STORAGE_KEY, currentLocale); } catch { /* no-op */ }
  document.documentElement.lang = currentLocale;
  return currentLocale;
}

export function t(key, variables = {}) {
  const value = messages[currentLocale][key] ?? messages.ko[key] ?? key;
  return interpolate(value, variables);
}

export function localizeTool(tool) {
  const localized = { ...tool };
  localized.label = t(`tool.${tool.op}.label`);
  localized.help = t(`tool.${tool.op}.help`);
  localized.fields = tool.fields.map((field) => ({
    ...field,
    label: fieldLabels[currentLocale]?.[field.label] || messages[currentLocale][`field.${field.name}`] || field.label,
    value: toolDefaults[currentLocale]?.[`${tool.op}.${field.name}`] ?? field.value,
    optionLabels: field.options?.reduce((result, value) => ({ ...result, [value]: optionLabels[currentLocale]?.[value] || value }), {}),
  }));
  return localized;
}

export function applyTranslations(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((element) => {
    element.textContent = t(element.dataset.i18n);
  });
  root.querySelectorAll('[data-i18n-html]').forEach((element) => {
    element.innerHTML = t(element.dataset.i18nHtml);
  });
  root.querySelectorAll('[data-i18n-aria-label]').forEach((element) => {
    element.setAttribute('aria-label', t(element.dataset.i18nAriaLabel));
  });
  root.querySelectorAll('[data-i18n-title]').forEach((element) => {
    element.setAttribute('title', t(element.dataset.i18nTitle));
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((element) => {
    element.setAttribute('placeholder', t(element.dataset.i18nPlaceholder));
  });
  root.querySelectorAll('[data-i18n-content]').forEach((element) => {
    element.setAttribute('content', t(element.dataset.i18nContent));
  });
  const languageSelect = root.getElementById?.('languageSelect') || root.querySelector?.('#languageSelect');
  if (languageSelect) {
    languageSelect.value = currentLocale;
    languageSelect.setAttribute('aria-label', t('language.label'));
  }
  document.title = currentLocale === 'ko' ? 'Academic PDF Editor' : 'Academic PDF Editor';
  document.documentElement.lang = currentLocale;
}

